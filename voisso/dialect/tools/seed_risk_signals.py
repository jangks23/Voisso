def _fuse_bieup(pattern: str) -> str | None:
    """받침 없는 음절로 끝나는 패턴에 ㅂ을 붙인 형태를 만든다.

    한국어는 어간에 "-ㅂ니다"가 붙으면 종성이 융합된다. "일어나" + ㅂ니더 → "일어납니더".
    그래서 부분 문자열 매칭이 끊긴다 — "일어나"는 "일어납니더"의 부분 문자열이 아니다.
    안전 데이터에서 이걸 손으로 챙기면 반드시 빠뜨리므로 생성 시점에 자동으로 만든다.
    """
    if not pattern:
        return None
    last = pattern[-1]
    code = ord(last) - 0xAC00
    if not (0 <= code <= 11171) or code % 28 != 0:
        return None
    return pattern[:-1] + chr(ord(last) + 17)


def _expand(patterns: list[str]) -> list[str]:
    out = list(patterns)
    for pattern in patterns:
        fused = _fuse_bieup(pattern)
        if fused and fused not in out:
            out.append(fused)
    return out


