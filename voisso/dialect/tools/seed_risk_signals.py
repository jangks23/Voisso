def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="risk_signals.json 생성")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("-o", "--output", type=Path, default=OUT_PATH)
