#: 길이 상한. 자막 기준이다.
SHORT_FORM_LIMITS = {"short": 24, "normal": 40, "emergency_short": 20, "emergency_normal": 30}

# --------------------------------------------------------------------------- #
# 빌드
# --------------------------------------------------------------------------- #
VALID_PREFIXES = ("curated:", "wikipedia:", "nikl:")


def build() -> dict:
    """튜플 목록을 lexicon.json 스키마로 펼친다. 검증도 여기서 한다."""
    problems: list[str] = []
    seen: set[str] = set()

    entries = []
    for dialect, standard, pos, domain, source, opts in ENTRIES:
        if dialect == standard:
            problems.append(f"동일쌍(변환 없음): {dialect}")
            continue
        if dialect in seen:
            problems.append(f"중복 표제어: {dialect}")
            continue
        if not source.startswith(VALID_PREFIXES):
            problems.append(f"출처 접두사 위반: {dialect} → {source}")
        seen.add(dialect)
        item = {
            "dialect": dialect,
            "standard": standard,
            "pos": pos,
            "source": source,
            "domain": domain,
        }
        if "r" in opts:
            item["reverse"] = True
        if "s" in opts:
            item["stem"] = True
        entries.append(item)

    rules = []
    for pattern, replace, desc, source, direction, priority, roundtrip, strength in RULES:
        if not source.startswith(VALID_PREFIXES):
            problems.append(f"출처 접두사 위반(규칙): {desc} → {source}")
        rules.append({
            "pattern": pattern,
            "replace": replace,
            "desc": desc,
            "source": source,
            "dir": direction,
            "priority": priority,
            "roundtrip": roundtrip,
            "strength": strength,
        })

    if problems:
        for line in problems:
            print(f"  ! {line}", file=sys.stderr)
        raise SystemExit(f"사전 시드 검증 실패 — {len(problems)}건. 위 항목을 고쳐라.")

    return {
        "meta": {
            "version": "1.0.0",
            "region": "경상북도 (동남 방언)",
            "register": "정중체 — 어르신 대상 공공 민원 서비스",
            "honesty": (
                "방언 음향 모델을 학습시키지 않았다. 어휘·어미 사전 기반 결정론적 변환이다. "
                "AI Hub 방언 코퍼스(dataSetSn=119)에서 가져온 항목은 하나도 없다 "
                "(이용정책 제5항 제3자 제공 금지 — docs/DATA_LICENSE.md §1)."
            ),
            "entry_count": len(entries),
            "rule_count": len(rules),
            "cue_count": sum(len(v) for v in CUES.values()),
            "short_form_count": len(SHORT_FORMS),
            "admin_plain_count": len(ADMIN_PLAIN),
            "noun_final_count": len(NOUN_FINAL),
            "callback_cue_count": sum(len(v) for v in CALLBACK.values()),
            "license": "CC BY-SA 4.0 — voisso/dialect/SOURCES.md 참조",
        },
        "entries": entries,
        "rules": rules,
        # 아래 둘은 번역쌍이 아니다. entries/rules 소비자는 무시해도 된다.
        "short_forms": [
            {"id": sid, "category": cat, "short": short, "normal": normal}
            for sid, cat, short, normal in SHORT_FORMS
        ],
        "short_form_limits": SHORT_FORM_LIMITS,
        "cues": CUES,
        "callback": CALLBACK,
        "noun_final": [{"noun": a, "sentence": b} for a, b in NOUN_FINAL],
        "admin_plain": [
            {"admin": a, "plain": b, **({"note": n} if n else {})}
            for a, b, n in ADMIN_PLAIN
        ],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="lexicon.json 초기 시드 생성")
    parser.add_argument("--force", action="store_true",
                        help="기존 lexicon.json 을 덮어쓴다 (이후 수정분이 날아간다)")
    parser.add_argument("-o", "--output", type=Path, default=LEXICON_PATH)
    args = parser.parse_args(argv)

    if args.output.exists() and not args.force:
        print(f"{args.output} 가 이미 있다. 덮어쓰려면 --force. "
              f"(생성 이후에는 lexicon.json 이 원본이다)", file=sys.stderr)
        return 1

    data = build()
    args.output.write_text(
        json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    print(f"{args.output} 생성 — 어휘 {data['meta']['entry_count']}개 / "
          f"규칙 {data['meta']['rule_count']}개")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
