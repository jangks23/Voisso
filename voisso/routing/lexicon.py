def expand_query(tokens: list[str]) -> dict[str, float]:
    """질의 어절 목록 -> {검색어: 가중치}. 원어절 1.0, 확장어 0.45."""
    out: dict[str, float] = {}
    for token in tokens:
        out[token] = max(out.get(token, 0.0), 1.0)
    for token in tokens:
        for key, extras in SYNONYMS.items():
            # 질의 어절이 키를 **포함**할 때만 발동한다.
            # 반대 방향(어절이 키의 일부)을 허용하면 "지원"이 "재난지원금" 항목을
            # 깨워서 전혀 상관없는 재난 부서가 딸려 올라온다.
            if key not in token:
                continue
            for extra in extras:
                out.setdefault(extra, EXPANSION_WEIGHT)
    return out


def lexicon_size() -> int:
    return len(SYNONYMS)
