CONCEPTS_BY_ID = {c.id: c for c in CONCEPTS}


@dataclass(frozen=True)
class ConceptHit:
    concept: Concept
    matched: str          # 실제로 걸린 표현

    @property
    def id(self) -> str:
        return self.concept.id

    @property
    def jurisdiction(self) -> Jurisdiction:
        return self.concept.jurisdiction


def detect(text: str) -> list[ConceptHit]:
    """문장에서 걸리는 개념을 모두 찾는다."""
    if not text:
        return []
    norm = normalize(text)
    if not norm:
        return []
    hits: list[ConceptHit] = []
    for concept in CONCEPTS:
        for pattern in concept._compiled:
            m = pattern.search(norm)
            if m:
                hits.append(ConceptHit(concept=concept, matched=m.group(0).strip()))
                break

    # 더 구체적인 개념이 걸렸으면 일반 개념은 눌러 없앤다.
    suppressed: set[str] = set()
    for hit in hits:
        suppressed.update(hit.concept.suppresses)
    return [h for h in hits if h.id not in suppressed]


# 같은 개념 안에서도 앞에 적은 용어가 더 대표적이다.
#   drain_blocked -> ("하수도", "하수관로", "배수", ...) 순서에 의미가 있다.
# 뒤로 갈수록 가중치를 조금씩 낮춰, 대표 용어를 가진 부서가 위로 오게 한다.
TERM_DECAY = 0.06
TERM_FLOOR = 0.70


def admin_terms(hits: list[ConceptHit]) -> dict[str, float]:
    """개념 히트 -> {행정 용어: 가중치}. 시군 소관 개념은 용어를 내지 않는다.

    맥락이 해소된 모호 개념은 **용어를 내지 않는다.** "비만 오면 마당이 잠긴다"
    처럼 상시 배수 불량이 확인되면, flood_unclear 가 들고 있던 '자연재난·피해조사'
    까지 같이 넣어서는 안 된다. 모호 개념은 어디까지나 맥락이 없을 때 쓰는
    양다리 폴백이다.
    """
    fired = {h.id for h in hits}
    out: dict[str, float] = {}
    for hit in hits:
        if hit.jurisdiction in ("municipal", "external"):
            continue
        concept = hit.concept
        if concept.needs_context and fired & set(concept.resolved_by):
            continue                      # 맥락이 잡혔다 — 폴백 용어는 뺀다
        for i, term in enumerate(concept.admin_terms):
            weight = CONCEPT_WEIGHT * max(1.0 - TERM_DECAY * i, TERM_FLOOR)
            if weight > out.get(term, 0.0):
                out[term] = weight
    return out


def external_hits(hits: list[ConceptHit]) -> list[ConceptHit]:
    """지자체 소관이 아닌 개념(가스 누출 등). 안전 사안이라 하나만 걸려도 알린다."""
    return [h for h in hits if h.jurisdiction == "external"]


def external_only(hits: list[ConceptHit]) -> bool:
    """걸린 개념이 전부 관할 밖이면 True — 도청 부서를 배정하지 않는다."""
    return bool(hits) and all(h.jurisdiction == "external" for h in hits)


def external_note(hits: list[ConceptHit]) -> str:
    notes = [h.concept.note for h in external_hits(hits) if h.concept.note]
    return " ".join(dict.fromkeys(notes))


def municipal_only(hits: list[ConceptHit]) -> bool:
    """걸린 개념이 전부 시군 소관이면 True (부서를 배정하면 안 된다)."""
    return bool(hits) and all(h.jurisdiction == "municipal" for h in hits)


def referral_note(hits: list[ConceptHit]) -> str:
    notes = [h.concept.note for h in hits if h.jurisdiction == "municipal" and h.concept.note]
    if not notes:
        return MUNICIPAL_NOTE
    head = notes[0].rstrip()
    if not head.endswith((".", "다", "요")):
        head += "."
    elif head.endswith("다"):
        head += "."
    return f"{head} {MUNICIPAL_NOTE}"


def shared_notes(hits: list[ConceptHit]) -> list[str]:
    return [h.concept.note for h in hits if h.jurisdiction == "shared" and h.concept.note]


def unresolved_context(hits: list[ConceptHit]) -> Concept | None:
    """맥락이 필요한데 해소 신호가 없는 개념을 돌려준다. 없으면 None.

    예) "집이 물에 잠겼어요" -> flood_unclear 만 걸리고 상시(flood_chronic)도
        재난(storm_damage)도 안 걸렸다 -> 단정하면 안 된다.
    """
    fired = {h.id for h in hits}
    for hit in hits:
        concept = hit.concept
        if not concept.needs_context:
            continue
        if fired & set(concept.resolved_by):
            continue
        return concept
    return None


def concept_count() -> int:
    return len(CONCEPTS)
