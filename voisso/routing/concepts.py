@dataclass(frozen=True)
class Concept:
    id: str
    label: str
    patterns: tuple[str, ...]
    admin_terms: tuple[str, ...] = ()
    jurisdiction: Jurisdiction = "province"
    note: str = ""
    # 같은 말이라도 맥락에 따라 소관이 갈리는 개념. 아래 개념 중 하나가 함께
    # 걸리지 않으면 단정하지 않고 후보를 여러 개 낸다.
    #   "집이 물에 잠겼어요" -> 상시 배수 불량인가, 호우 재난 피해인가?
    needs_context: str = ""
    resolved_by: tuple[str, ...] = ()
    # 더 구체적인 개념이 걸리면 눌러야 할 개념들.
    #   "가스 냄새" 는 gas_leak 이지 odor_noise(공장 악취)가 아니다.
    suppresses: tuple[str, ...] = ()
    _compiled: tuple[re.Pattern, ...] = field(default=(), repr=False, compare=False)


def _c(
    cid: str,
    label: str,
    patterns: tuple[str, ...],
    admin_terms: tuple[str, ...] = (),
    jurisdiction: Jurisdiction = "province",
    note: str = "",
    needs_context: str = "",
    resolved_by: tuple[str, ...] = (),
    suppresses: tuple[str, ...] = (),
) -> Concept:
    return Concept(
        id=cid,
        label=label,
        patterns=patterns,
        admin_terms=admin_terms,
        jurisdiction=jurisdiction,
        note=note,
        needs_context=needs_context,
        resolved_by=resolved_by,
        suppresses=suppresses,
        _compiled=tuple(re.compile(p) for p in patterns),
    )


